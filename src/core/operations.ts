/**
 * Core arithmetic operations module for the calculator.
 * Contains pure functions for add, subtract, multiply, and divide operations.
 * Migrated from Python arithmetic functions (actionPlus, actionMinus, actionMul, actionDiv).
 */

/**
 * Adds two numbers and returns the result.
 *
 * @param a - First number
 * @param b - Second number
 * @returns The sum of a and b
 */
export function add(a: number, b: number): number {
  return a + b;
}

/**
 * Subtracts the second number from the first and returns the result.
 * (Placeholder for Milestone 2)
 *
 * @param a - First number
 * @param b - Second number
 * @returns The difference of a and b
 */
export function subtract(a: number, b: number): number {
  return a - b;
}

/**
 * Multiplies two numbers and returns the result.
 * (Placeholder for Milestone 2)
 *
 * @param a - First number
 * @param b - Second number
 * @returns The product of a and b
 */
export function multiply(a: number, b: number): number {
  return a * b;
}

/**
 * Divides the first number by the second and returns the result.
 * (Placeholder for Milestone 2)
 *
 * @param a - First number (dividend)
 * @param b - Second number (divisor)
 * @returns The quotient of a divided by b
 */
export function divide(a: number, b: number): number {
  return a / b;
}
